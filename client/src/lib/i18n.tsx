export function localizeCase(item: PortfolioCase, language: Language): PortfolioCase {
  const localized = caseTranslations[item.slug]?.[language];
  return localized ? { ...item, ...localized } : item;
}

type I18nValue = { language: Language; setLanguage: (language: Language) => void; toggleLanguage: () => void; t: (key: string) => string };
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "pt";
    return window.localStorage.getItem("marcelle-language") === "en" ? "en" : "pt";
  });

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem("marcelle-language", nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage(language === "pt" ? "en" : "pt"),
    t: (key: string) => translations[language][key] ?? translations.pt[key] ?? key,
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
